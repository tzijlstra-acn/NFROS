/**
 * Personal work layer: inbox, calendar, meetings, the two live meeting scripts
 * and the simulated outbound collaboration messages.
 *
 * Authoritative source: docs/SCENARIO_BIBLE.md sections 1, 2, 2.1, 3, 4, 6, 7,
 * 8, 9, 10, 11, 12, 14 and 15. Where this module and the bible disagree, the
 * bible wins and this module is fixed.
 *
 * Two properties of this module are easy to miss and both are deliberate.
 *
 * First, every outbound message in `collaborationMessages` is simulated. The
 * product composes it, records it and seeds a reply. Nothing leaves the
 * machine. `simulatedOnly` is written explicitly on every row so the trust
 * page can prove that rather than assert it.
 *
 * Second, `confirmedTriage` is null on every inbox row, and `flagDismissed`
 * and `correctionRecorded` are false on every meeting turn. Those three fields
 * are the human's act. Seeding them would mean seeding the decision the
 * product exists to leave with a person.
 *
 * Identifier note. Inbox messages, calendar entries, meetings, meeting turns
 * and collaboration messages are interface-layer objects rather than entries
 * in the bible's object register, so they carry their own type prefixes
 * (`IMSG`, `CAL`, `MTG`, `MTM`, `COL`) under the same TYPE-SCOPE-SEQUENCE
 * pattern defined in section 1.
 *
 * Reveal note. `revealedAtMoment` only ever holds one of the ten moment times
 * from section 2.1, because that is what the clock can scrub to. The precise
 * minute a message actually landed lives in `receivedAt`. A 14:34 arrival is
 * therefore revealed in the 14:05 bucket and still displays its real time.
 *
 * Synthetic institution and data. All persons are fictional.
 */

